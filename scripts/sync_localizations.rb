english.each do |key, value|
  entry = strings[key] ||= {}
  if check_only
    actual = entry.dig("localizations", "en", "stringUnit", "value")
    abort "English translation drift for #{key.inspect}: #{actual.inspect}" unless actual == value
    next
  end
  entry["localizations"] ||= {}
  entry["localizations"]["en"] = {
    "stringUnit" => {
      "state" => "translated",
      "value" => value
    }
  }
end

